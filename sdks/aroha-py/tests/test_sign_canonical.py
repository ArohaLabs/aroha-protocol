"""sign_canonical / verify_canonical — the bare-signature counterpart to
sign_message/verify_message_signature, mirroring signCanonical /
verifyCanonicalSignature in aroha-core/src/crypto/signing.ts.

TestCrossLanguage's vector was produced by that TypeScript implementation
(see the sibling PR/commit) — proof the two languages agree on what bytes
actually get signed, not just that each is internally consistent.
"""

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey

from aroha.crypto import sign_canonical, verify_canonical


def test_sign_canonical_produces_bare_hex_signature():
    key = Ed25519PrivateKey.generate()
    payload = {"firmDid": "did:aroha:acme", "subdomain": "acme", "timestamp": "2026-01-01T00:00:00.000Z"}

    sig = sign_canonical(payload, key)

    assert isinstance(sig, str)
    assert len(sig) == 128  # 64 bytes, hex
    assert verify_canonical(payload, sig, key.public_key())


def test_verify_canonical_rejects_tampered_payload():
    key = Ed25519PrivateKey.generate()
    payload = {"amount": 100}
    sig = sign_canonical(payload, key)
    assert verify_canonical({"amount": 999}, sig, key.public_key()) is False


def test_verify_canonical_rejects_wrong_key():
    key = Ed25519PrivateKey.generate()
    other = Ed25519PrivateKey.generate()
    payload = {"x": 1}
    sig = sign_canonical(payload, key)
    assert verify_canonical(payload, sig, other.public_key()) is False


def test_verify_canonical_rejects_malformed_hex_without_raising():
    key = Ed25519PrivateKey.generate()
    assert verify_canonical({"x": 1}, "not-hex", key.public_key()) is False
    assert verify_canonical({"x": 1}, "ab", key.public_key()) is False  # too short


class TestCrossLanguage:
    """Vector generated by @aroha-sdk/core's signCanonical (TypeScript)."""

    PRIVATE_KEY_HEX = "07" * 32
    PUBLIC_KEY_HEX = "ea4a6c63e29c520abef5507b132ec5f9954776aebebe7b92421eea691446d22c"
    PAYLOAD = {"firmDid": "did:aroha:acme-cpa", "subdomain": "acme", "timestamp": "2026-01-01T00:00:00.000Z"}
    SIGNATURE_HEX = (
        "875aae3fab2d8f9b5fa0ce392784cc0c4138922d2fa008d943f8e8fecedd93a"
        "875c0e4257c31d67fb76bc6bd21e42e06597820e96176d4ee501be761b9f4b10f"
    )

    def test_python_verifies_a_typescript_signature(self):
        pub = Ed25519PublicKey.from_public_bytes(bytes.fromhex(self.PUBLIC_KEY_HEX))
        assert verify_canonical(self.PAYLOAD, self.SIGNATURE_HEX, pub) is True

    def test_python_produces_the_same_signature_typescript_did(self):
        priv = Ed25519PrivateKey.from_private_bytes(bytes.fromhex(self.PRIVATE_KEY_HEX))
        assert sign_canonical(self.PAYLOAD, priv) == self.SIGNATURE_HEX
