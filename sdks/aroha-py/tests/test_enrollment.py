@needs_vectors
def test_vector_signatures():
    assert V["purpose"] == ENROLLMENT_PURPOSE
    for s in V["signatures"]:
        i = s["input"]
        assert enrollment_signing_payload(audience=i["audience"], account_id=i["accountId"], did=i["did"], challenge=i["challenge"]) == s["payload"]
        priv = bytes.fromhex(V["keys"][s["signer"]]["privateKeyHex"])
        assert sign_enrollment(account_id=i["accountId"], did=i["did"], challenge=i["challenge"], audience=i["audience"], private_key=priv) == s["proof"]


@needs_vectors
@pytest.mark.parametrize("case", V["cases"] if V else [], ids=lambda c: c["name"])
def test_vectors(case):
    store = InMemoryEnrollmentStore()
    for i, s in enumerate(case["steps"]):
        if "seed" in s:
            sd = s["seed"]
            store.put_challenge(sd["challenge"], EnrollmentChallengeRecord(sd["accountId"], parse_iso_ms(sd["expiresAt"])), parse_iso_ms(V["now"]))
        elif "enrolled" in s:
            assert enrolled_did(store, s["enrolled"]) == s["expected"], f"{case['name']} step {i}"
        else:
            c = s["complete"]
            r = complete_enrollment(
                store, authenticated_account_id=c["authenticatedAccountId"], audience=c.get("audience", V["audience"]),
                did=c.get("did"), challenge=c.get("challenge"), proof=c.get("proof"), now=parse_iso_ms(c.get("now", V["now"])),
            )
            if r.ok:
                got = {"ok": True, "did": r.did, **({"replaced": r.replaced} if r.replaced is not None else {})}
            else:
                got = {"ok": False, "code": r.code, "status": r.status}
            assert got == s["expected"], f"{case['name']} step {i}: {r.reason}"
