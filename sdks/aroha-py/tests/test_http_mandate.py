def test_legacy_task_body_is_not_a_spending_mandate():
    body = {
        "mandateType": "hybrid", "mandateTier": "intent", "constraints": {"spendLimitUsd": 1000},
        "grantee": AGENT.did, "grantor": HUMAN.did,
        "issuedAt": iso_ms(now_ms() - 1000), "expiresAt": iso_ms(now_ms() + 600_000),
        "parentMandateId": None, "mandateId": "00000000-0000-4000-8000-0000000000aa",
    }
    sig = HUMAN.priv.sign(js_stringify_sorted(body).encode())
    v1 = b64u(json.dumps({"mandate": body, "signature": b64u(sig)}).encode())
    r = verify_mandate(v1, HUMAN.pub)
    assert not r.valid and "mandateType" in r.reason
    with pytest.raises(SpendingConstraintViolation) as e:
        enforce_spending_constraints(v1, HUMAN.pub, proposed_amount_usd=10, expected_root=HUMAN.did)
    assert e.value.code == "MANDATE_INVALID"


@pytest.mark.parametrize("amount", [math.nan, -1, -0.01, math.inf, -math.inf, "10", None, True])
def test_enforce_refuses_bad_amounts(amount):
    with pytest.raises(SpendingConstraintViolation) as e:
        enforce_spending_constraints(TOKEN, HUMAN.pub, proposed_amount_usd=amount)
    assert e.value.code == "INVALID_AMOUNT"


# ── Cross-SDK vectors ─────────────────────────────────────────────────────────

def _vctx(v, nonces=None):
    return dict(audience=v["audience"], method=v["method"], url=v["url"], body=unb64u(v["body"]),
                now=parse_iso_ms(v["now"]), nonces=nonces if nonces is not None else InMemoryHttpPresentationNonces())


@needs_vectors
def test_vector_constants():
    assert V["header"] == HTTP_MANDATE_HEADER
    assert V["purpose"] == HTTP_MANDATE_PRESENTATION_PURPOSE


@needs_vectors
def test_vector_presentations_byte_for_byte():
    assert len(V["presentations"]) >= 4
    for c in V["presentations"]:
        p, e, k = c["present"], c["expected"], V["keys"][c["present"]["holder"]]
        token = V["tokens"][p["token"]]
        assert http_method_for_proof(p["method"]) == e["method"], c["name"]
        assert http_request_target(p["url"]) == e["target"], c["name"]
        assert http_request_target(c["verify"]["url"]) == e["target"], c["name"]
        assert http_body_sha256(unb64u(p["body"])) == e["bodySha256"], c["name"]
        mandate_id = json.loads(unb64u(token))["mandate"]["mandateId"]
        assert http_presentation_signing_payload(
            audience=V["audience"], method=e["method"], target=e["target"], body_sha256=e["bodySha256"],
            mandate_id=mandate_id, holder=k["did"], nonce=p["nonce"], expires=e["expires"],
        ) == e["signingPayload"], c["name"]
        h = present_mandate_http(
            token=token, holder_did=k["did"], holder_private_key=bytes.fromhex(k["privateKeyHex"]),
            audience=V["audience"], method=p["method"], url=p["url"], body=unb64u(p["body"]),
            ttl_ms=p["ttlMs"], nonce=p["nonce"], now=parse_iso_ms(V["presentedAt"]),
        )[HTTP_MANDATE_HEADER]
        assert h == e["headerValue"], c["name"]
        assert unb64u(h).decode() == e["headerJson"], c["name"]
        r = verify_http_presentation(h, **_vctx(c["verify"]))
        assert r.ok and r.holder == e["verify"]["holder"], (c["name"], r.reason)


@needs_vectors
def test_vector_refusals():
    assert len(V["refusals"]) >= 25
    for c in V["refusals"]:
        r = verify_http_presentation(c["headerValue"], **_vctx(c["verify"]))
        assert (r.ok, r.code) == (False, c["expectedCode"]), (c["name"], r.reason)


@needs_vectors
def test_vector_replay():
    c = V["replay"]
    nonces = InMemoryHttpPresentationNonces()
    codes = []
    for _ in c["expectedCodes"]:
        r = verify_http_presentation(c["headerValue"], **_vctx(c["verify"], nonces))
        codes.append(None if r.ok else r.code)
    assert codes == c["expectedCodes"]


@needs_vectors
def test_vector_mandate_requests():
    for c in V["mandateRequests"]:
        kwargs = _vctx(c["verify"])
        if "expectedRoot" in c:
            kwargs["expected_root"] = c["expectedRoot"]
        if "trustedRoots" in c:
            kwargs["trusted_roots"] = c["trustedRoots"]
        r = verify_http_mandate_request(c["headerValue"], is_revoked=None, **kwargs)
        summary = (
            {"ok": True, "holder": r.holder, "rootGrantor": r.root_grantor, "mandateId": r.mandate.mandate_id}
            if r.ok else {"ok": False, "code": r.code, "status": r.status}
        )
        assert summary == c["expected"], c["name"]
