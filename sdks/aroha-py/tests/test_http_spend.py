@needs_vectors
def test_vector_ledger_keys():
    for m in V["mandates"].values():
        assert m["ledgerKey"] == mandate_redemption_key(m["mandate"])


@needs_vectors
@pytest.mark.parametrize("case", V["cases"] if V else [], ids=lambda c: c["name"])
def test_vectors(case):
    ledger = InMemorySpendingLedger()
    nonces = InMemoryHttpPresentationNonces()
    results = []
    for i, s in enumerate(case["steps"]):
        if "release" in s:
            r = results[s["release"]]
            assert r.ok
            r.charge.release()
            results.append(r)
            continue
        amount = float(s["amountFloat"]) if "amountFloat" in s else s.get("amountUsd")
        r = verify_http_spend_request(
            s["headerValue"], audience=V["audience"], method=s.get("method", "POST"), url=V["url"],
            body=V["body"].encode("utf-8"), nonces=nonces, now=parse_iso_ms(s.get("now", V["now"])),
            expected_root=s.get("expectedRoot", V["keys"]["human"]["did"]), is_revoked=None, ledger=ledger,
            amount_usd=amount, currency=s.get("currency"), merchant=s.get("merchant"),
            merchant_category=s.get("merchantCategory"), human_approved=s.get("humanApproved"),
        )
        results.append(r)
        got = ({"ok": True, "chargedKeys": [k for k, _ in r.charge.allocations]} if r.ok
               else {"ok": False, "code": r.code, "status": r.status})
        assert got == s["expected"], f"{case['name']} step {i}: {r.reason}"
    for name, m in V["mandates"].items():
        st = ledger.status(m["ledgerKey"])
        assert (st.allocated_usd if st else 0) == case["expectedTotals"].get(name, 0), f"{case['name']} total for {name}"
