var arohaContext = []string{
	"https://aroha-labs.com/contexts/v1",
	"https://w3id.org/security/suites/ed25519-2020/v1",
}

// DefaultEnvelopeTTL is Build's default lifetime (TS buildEnvelope: 300 s).
const DefaultEnvelopeTTL = 5 * time.Minute

// DefaultMaxEnvelopeTTL is the default ceiling on an envelope's declared
// lifetime (expires - created). It equals the default TTL, so default
// envelopes pass while a sender cannot choose a 30-day replay window. Raise
// it only together with a persistent or shared NonceStore.
const DefaultMaxEnvelopeTTL = 5 * time.Minute

// DefaultMaxFutureSkew is the default allowance for a sender's clock running
// ahead of ours when checking `created`.
const DefaultMaxFutureSkew = 30 * time.Second

// reservedFields are generated by Build and cannot be supplied as extras —
// overriding "expires" would bypass the TTL ceiling, "from" the signer, etc.
var reservedFields = map[string]bool{
	"@context": true, "id": true, "type": true, "from": true, "to": true, "created": true,
	"expires": true, "nonce": true, "correlationId": true, "body": true, "proof": true,
}

// BuildOptions configures BuildWithOptions.
type BuildOptions struct {
	// TTL is how long the envelope is valid. 0 means DefaultEnvelopeTTL.
	TTL time.Duration
	// AllowLongTTL permits TTL > DefaultMaxEnvelopeTTL. Receivers reject such
	// envelopes unless configured with a matching ValidateOptions.MaxTTL.
	AllowLongTTL bool
	// KeyID is the verification method stamped into proof.verificationMethod.
	// Default "<from>#key-1".
	KeyID string
	// Traceparent is the W3C Trace Context header, if any.
	Traceparent string
	// RoutingHint is the informational model-routing hint, if any.
	RoutingHint map[string]any
	// Disclosure is the per-hop AI / principal disclosure to carry, signed
	// with the rest of the envelope. Its AgentDID must equal fromDID.
	Disclosure *Disclosure
	// Extra adds further top-level fields. Reserved envelope fields are rejected.
	Extra map[string]any
}

// BuildWithOptions constructs and signs an Aroha envelope.
func BuildWithOptions(
	msgType, fromDID, toDID string,
	body map[string]any,
	correlationID string,
	privateKey ed25519.PrivateKey,
	opts BuildOptions,
) (map[string]any, error) {
	ttl := opts.TTL
	if ttl == 0 {
		ttl = DefaultEnvelopeTTL
	}
	if ttl < 0 {
		return nil, fmt.Errorf("envelope ttl must be positive, got %s", ttl)
	}
	if ttl > DefaultMaxEnvelopeTTL && !opts.AllowLongTTL {
		return nil, fmt.Errorf("envelope ttl %s exceeds the default receiver maximum %s; set AllowLongTTL to override",
			ttl, DefaultMaxEnvelopeTTL)
	}
	if len(privateKey) != ed25519.PrivateKeySize {
		return nil, fmt.Errorf("private key is %d bytes, want %d", len(privateKey), ed25519.PrivateKeySize)
	}
	if body == nil {
		body = map[string]any{}
	}
	now := time.Now().UTC()
	envelope := map[string]any{
		"@context":      arohaContext,
		"id":            "urn:uuid:" + uuid.New().String(),
		"type":          msgType,
		"from":          fromDID,
		"to":            toDID,
		"created":       now.Format(identity.ISOTimeLayout),
		"expires":       now.Add(ttl).Format(identity.ISOTimeLayout),
		"nonce":         randomNonce(),
		"correlationId": correlationID,
		"body":          body,
	}
	if opts.Traceparent != "" {
		envelope["traceparent"] = opts.Traceparent
	}
	if opts.RoutingHint != nil {
		envelope["routingHint"] = opts.RoutingHint
	}
	if opts.Disclosure != nil {
		envelope["disclosure"] = opts.Disclosure.Map()
	}
	for k, v := range opts.Extra {
		if reservedFields[k] {
			return nil, fmt.Errorf("extra field %q is reserved", k)
		}
		envelope[k] = v
	}
	if d, present := envelope["disclosure"]; present {
		if _, err := ValidateDisclosure(d, fromDID); err != nil {
			return nil, fmt.Errorf("Invalid disclosure: %w", err)
		}
	}
	keyID := opts.KeyID
	if keyID == "" {
		keyID = fromDID + "#key-1"
	}
	if err := crypto.SignMessage(envelope, privateKey, keyID); err != nil {
		return nil, fmt.Errorf("sign envelope: %w", err)
	}
	return envelope, nil
}

// Build constructs and signs a Aroha envelope.
//
//   - msgType:       e.g. "ArohaRequest"
//   - fromDID:       sender's DID
//   - toDID:         recipient's DID
//   - body:          message body map
//   - correlationID: saga or session ID
//   - privateKey:    sender's Ed25519 private key
//   - keyID:         verification method ID, e.g. "did:aroha:alice#key-1"
//   - ttl:           time-to-live; must be in (0, DefaultMaxEnvelopeTTL]. Use
//     BuildWithOptions with AllowLongTTL for a longer one.
//   - extraFields:   optional extra top-level fields (e.g. traceparent,
//     routingHint). Reserved envelope fields cannot be overridden.
func Build(
	msgType, fromDID, toDID string,
	body map[string]any,
	correlationID string,
	privateKey ed25519.PrivateKey,
	keyID string,
	ttl time.Duration,
	extraFields ...map[string]any,
) (map[string]any, error) {
	if ttl <= 0 {
		return nil, fmt.Errorf("envelope ttl must be positive, got %s", ttl)
	}
	extra := map[string]any{}
	for _, m := range extraFields {
		for k, v := range m {
			extra[k] = v
		}
	}
	return BuildWithOptions(msgType, fromDID, toDID, body, correlationID, privateKey, BuildOptions{
		TTL: ttl, KeyID: keyID, Extra: extra,
	})
}

// BuildDefault calls Build with a 5-minute TTL and no extra fields.
func BuildDefault(
	msgType, fromDID, toDID string,
	body map[string]any,
	correlationID string,
	privateKey ed25519.PrivateKey,
	keyID string,
) (map[string]any, error) {
	return Build(msgType, fromDID, toDID, body, correlationID, privateKey, keyID, DefaultEnvelopeTTL)
}

// MaxNonceLength is the longest nonce Validate accepts. Envelopes built by
// any Aroha SDK carry 64 hex characters; the cap bounds what a sender can
// make the replay store hold per message.
const MaxNonceLength = 128

// ValidationError describes why an envelope was rejected.
type ValidationError struct {
	// Code is the wire error code to answer with.
	Code   ErrorCode
	Reason string
}

func (e *ValidationError) Error() string { return "envelope invalid: " + e.Reason }

func reject(code ErrorCode, format string, args ...any) error {
	return &ValidationError{Code: code, Reason: fmt.Sprintf(format, args...)}
}

// ValidateOptions controls which checks Validate performs.
type ValidateOptions struct {
	// SkipSignature disables Ed25519 signature verification. Use only inside a
	// trusted network (mTLS / VPC). The nonce is still recorded, keyed by the
	// CLAIMED sender, so replay protection is only as good as that network.
	//
	// It MUST be paired with a transport-level check that authenticates the
	// peer. Validate refuses it (an error wrapping ErrDevModeNotPermitted)
	// unless AcknowledgeUnauthenticated is also set or the environment sets
	// AROHA_DEV_MODE=1 (a warning is printed to stderr once).
	SkipSignature bool
	// AcknowledgeUnauthenticated states that a transport-level check (mTLS, a
	// private link, a signed-request layer) authenticates the peer, which is
	// what makes SkipSignature acceptable outside dev mode.
	AcknowledgeUnauthenticated bool
	// ClockTolerance accepts envelopes that expired up to this long ago.
	// Default 0 (strict). Must not be negative.
	ClockTolerance time.Duration
	// MaxTTL is the maximum accepted expires - created. 0 = DefaultMaxEnvelopeTTL.
	MaxTTL time.Duration
	// MaxFutureSkew is how far `created` may be in the future.
	// nil = max(ClockTolerance, DefaultMaxFutureSkew).
	MaxFutureSkew *time.Duration
	// Now overrides the current time (tests). Zero = time.Now().
	Now time.Time
}

func didOfVerificationMethod(vmID string) (string, bool) {
	if strings.HasPrefix(vmID, "#") {
		return "", false // relative: belongs to whichever DID resolves it
	}
	if i := strings.Index(vmID, "#"); i >= 0 {
		return vmID[:i], true
	}
	return vmID, true
}

// Validate checks an incoming envelope, in the same order as
// @aroha-sdk/core validateEnvelope:
//
//  1. recipient: `to` must equal myDID;
//  2. timestamps (no state touched): created/expires parse; not expired
//     (with ClockTolerance); created not beyond MaxFutureSkew; declared
//     lifetime expires - created <= MaxTTL; nonce present;
//  3. signature (unless SkipSignature), and the proof's verification
//     method must belong to `from`;
//  4. nonce freshness, recorded ONLY NOW and keyed per sender
//     ("<from>:<nonce>"), retained until expires + ClockTolerance.
//
// Signature before nonce means unauthenticated traffic can neither fill the
// nonce store nor pre-burn a legitimate sender's nonce. Returns nil on
// success, *ValidationError on rejection.
func Validate(
	envelope map[string]any,
	senderPubKey ed25519.PublicKey,
	myDID string,
	nonces *NonceRegistry,
	opts ...ValidateOptions,
) error {
	var o ValidateOptions
	if len(opts) > 0 {
		o = opts[0]
	}
	if nonces == nil {
		return errors.New("envelope validation needs a NonceRegistry")
	}
	if o.SkipSignature && !o.AcknowledgeUnauthenticated {
		if err := RequireDevMode("messages.ValidateOptions.SkipSignature"); err != nil {
			return err
		}
	}

	// 1. Recipient
	to, _ := envelope["to"].(string)
	if to != myDID {
		return reject(ErrUnauthorized, "Message addressed to %s, not %s", to, myDID)
	}

	// 2. Timestamps
	if o.ClockTolerance < 0 {
		return reject(ErrInvalidParams, "Invalid clockToleranceMs: must be non-negative")
	}
	createdStr, _ := envelope["created"].(string)
	expiresStr, _ := envelope["expires"].(string)
	created, cerr := identity.ParseISOTime(createdStr)
	expires, eerr := identity.ParseISOTime(expiresStr)
	if cerr != nil || eerr != nil {
		return reject(ErrInvalidParams, "Malformed created/expires timestamp")
	}
	now := o.Now
	if now.IsZero() {
		now = time.Now()
	}
	nowMs, createdMs, expiresMs := now.UnixMilli(), created.UnixMilli(), expires.UnixMilli()
	tolMs := o.ClockTolerance.Milliseconds()
	if expiresMs+tolMs < nowMs {
		return reject(ErrExpiredMessage, "Message expired at %s (outside tolerance window)", expiresStr)
	}
	skew := DefaultMaxFutureSkew
	if o.ClockTolerance > skew {
		skew = o.ClockTolerance
	}
	if o.MaxFutureSkew != nil {
		skew = *o.MaxFutureSkew
	}
	if createdMs > nowMs+skew.Milliseconds() {
		return reject(ErrInvalidParams, "Message created at %s is in the future (beyond allowed clock skew)", createdStr)
	}
	maxTTL := o.MaxTTL
	if maxTTL == 0 {
		maxTTL = DefaultMaxEnvelopeTTL
	}
	if expiresMs-createdMs > maxTTL.Milliseconds() {
		return reject(ErrInvalidParams, "Message lifetime %dms exceeds maximum %dms", expiresMs-createdMs, maxTTL.Milliseconds())
	}
	nonce, _ := envelope["nonce"].(string)
	if nonce == "" {
		return reject(ErrInvalidParams, "Missing nonce")
	}
	if len([]rune(nonce)) > MaxNonceLength {
		return reject(ErrInvalidParams, "Nonce too long (max %d characters)", MaxNonceLength)
	}
	from, _ := envelope["from"].(string)

	// A disclosure is optional, but one that is present must be well-formed
	// and made in the sender's own name.
	if d, present := envelope["disclosure"]; present {
		if _, err := ValidateDisclosure(d, from); err != nil {
			return reject(ErrInvalidParams, "Invalid disclosure: %s", err.Error())
		}
	}

	// 3. Signature — BEFORE the nonce is recorded.
	if !o.SkipSignature {
		if proof, ok := envelope["proof"].(map[string]any); ok {
			if vm, _ := proof["verificationMethod"].(string); vm != "" {
				if vmDID, abs := didOfVerificationMethod(vm); abs && vmDID != from {
					return reject(ErrInvalidSignature,
						"Signature verification failed: proof key belongs to a different DID than `from`")
				}
			}
		}
		ok, err := crypto.VerifyMessageSignature(envelope, senderPubKey)
		if err != nil || !ok {
			return reject(ErrInvalidSignature, "Signature verification failed")
		}
	}

	// 4. Nonce (replay prevention), per sender. Retained until
	// expires + tolerance: the expiry check above keeps accepting the
	// envelope that long, so evicting at `expires` would reopen a window.
	fresh, err := nonces.CheckKey(from+":"+nonce, time.UnixMilli(expiresMs+tolMs))
	if err != nil {
		return reject(ErrInternalError, "Nonce store error: %v", err)
	}
	if !fresh {
		return reject(ErrReplayDetected, "Nonce replay detected")
	}
	return nil
}

// NewCorrelationID generates a random saga / session correlation ID
// ("saga-<uuid>", as TS newCorrelationId).
func NewCorrelationID() string {
	return "saga-" + uuid.New().String()
}

// randomNonce returns 32 random bytes, hex encoded (as TS buildEnvelope).
func randomNonce() string {
	b := make([]byte, 32)
	_, _ = rand.Read(b)
	return hex.EncodeToString(b)
}
