def test_body_that_cannot_be_a_jwt_is_refused() -> None:
    body = {"mandateTier": "intent", "constraints": {"spendLimitUsd": 1}, "grantee": "b", "grantor": "a",
            "issuedAt": "2026-01-01T00:00:00.250Z", "expiresAt": "2026-01-01T01:00:00.000Z", "parentMandateId": None, "mandateId": "m"}
    with pytest.raises(ValueError, match="whole second"):
        mandate_body_to_jwt_claims("spending", body)
    with pytest.raises(ValueError, match="type"):
        mandate_body_to_jwt_claims("spending", {**body, "issuedAt": "2026-01-01T00:00:00.000Z", "type": "x"})


