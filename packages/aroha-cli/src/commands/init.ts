import { join, resolve } from "node:path";
import { ask, choose, askList, confirm, closePrompts } from "../utils/prompt.js";
import { writeScaffold, dirExists, banner, success, fatal, log } from "../utils/scaffold.js";
import { providerTemplate } from "../templates/provider.js";
import { orchestratorTemplate } from "../templates/orchestrator.js";

export interface InitFlags {
  type?: "provider" | "orchestrator";
  port?: number;
  apiPort?: number;
  capabilities?: string[];
  yes?: boolean;
}

export async function runInit(name: string | undefined, flags: InitFlags): Promise<void> {
  banner("aroha init — scaffold a Aroha agent");

  if (!name) {
    name = await ask("Agent name", "my-aroha-agent");
  }

  // Sanitize name to a valid npm package / DID id
  const safeName = name.toLowerCase().replace(/[^a-z0-9-]/g, "-").replace(/^-+|-+$/g, "");
  if (safeName !== name) {
    log("info", `Name normalized to "${safeName}"`);
    name = safeName;
  }

  const outDir = resolve(process.cwd(), name);

  if (await dirExists(outDir)) {
    const overwrite = await confirm(`Directory "${name}" already exists. Overwrite?`, false);
    if (!overwrite) {
      log("skip", "Aborted.");
      closePrompts();
      return;
    }
  }

  const type = flags.type ?? (flags.yes ? "provider" : await choose("Agent type", ["provider", "orchestrator"], "provider"));

  let files: Map<string, string>;

  if (type === "provider") {
    const port = flags.port ?? (flags.yes ? 3001 : Number(await ask("Aroha port", "3001")));
    const capabilities =
      flags.capabilities ??
      (flags.yes
        ? ["search-items", "book-item"]
        : await askList("Capabilities", "e.g. search-flights,book-flight"));

    if (!capabilities.length) capabilities.push("search-items", "book-item");

    files = providerTemplate({ name, port, capabilities });
    log("info", `Provider with ${capabilities.length} capability(ies): ${capabilities.join(", ")}`);
  } else {
    const port = flags.port ?? (flags.yes ? 3000 : Number(await ask("Aroha port", "3000")));
    const apiPort = flags.apiPort ?? (flags.yes ? 3010 : Number(await ask("REST API port", "3010")));
    files = orchestratorTemplate({ name, port, apiPort });
    log("info", `Orchestrator with Aroha port ${port}, REST API port ${apiPort}`);
  }

  // In zero-config mode, append a generated DID to the scaffold
  if (flags.yes) {
    const did = `did:aroha:${name}`;
    const envContent = `# Auto-generated by aroha init --yes\n# Replace AROHA_PRIVATE_KEY with your real Ed25519 key in production\nAROHA_AGENT_DID=${did}\nAROHA_PRIVATE_KEY=\n`;
    files.set(".env.example", envContent);
    files.set(".env", envContent);
    log("info", `Auto-assigned DID: ${did}`);
  }

  closePrompts();
  await writeScaffold(outDir, files);

  success(`Created ${type} agent "${name}" in ./${name}/`);
  console.log("  Next steps:");
  console.log(`    cd ${name}`);
  console.log("    npm install");
  console.log("    npm run dev\n");
}
