def test_issue_and_enroll():
    store = InMemoryEnrollmentStore()
    t = parse_iso_ms("2026-06-01T12:00:00.000Z")
    c = issue_enrollment_challenge(store, authenticated_account_id="acct-1", now=t)
    assert len(c.challenge) == 43 and c.expires_at == "2026-06-01T12:05:00.000Z" and c.account_id == "acct-1"
    assert enrolled_did(store, "acct-1") is None
    proof = sign_enrollment(account_id="acct-1", did=ALICE.did, challenge=c.challenge, audience=AUD, private_key=ALICE.priv)
    r = complete_enrollment(store, authenticated_account_id="acct-1", audience=AUD, did=ALICE.did,
                            challenge=c.challenge, proof=proof, now=t + 299_999)
    assert (r.ok, r.account_id, r.did, r.replaced) == (True, "acct-1", ALICE.did, None)
    assert enrolled_did(store, "acct-1") == ALICE.did
    assert store.pending_challenges == 0


def test_refuses_the_mutations():
    store = InMemoryEnrollmentStore()
    r = enroll(store, "acct-A", ALICE, signed_in_as="acct-B")
    assert (r.ok, r.code, r.status) == (False, "CHALLENGE_ACCOUNT_MISMATCH", 403)
    c = issue_enrollment_challenge(store, authenticated_account_id="acct-A")
    by_mallory = b64u(MALLORY.priv.sign(enrollment_signing_payload(
        audience=AUD, account_id="acct-A", did=ALICE.did, challenge=c.challenge).encode()))
    r = complete_enrollment(store, authenticated_account_id="acct-A", audience=AUD, did=ALICE.did, challenge=c.challenge, proof=by_mallory)
    assert (r.code, r.status) == ("BAD_PROOF", 403)
    c2 = issue_enrollment_challenge(store, authenticated_account_id="acct-A")
    assert complete_enrollment(store, authenticated_account_id="acct-A", audience=AUD, did=ALICE.did,
                               challenge=c2.challenge, proof=None).code == "BAD_PROOF"
    assert enroll(store, "acct-A", ALICE, audience="https://other.example.com").code == "BAD_PROOF"
    assert enrolled_did(store, "acct-A") is None and enrolled_did(store, "acct-B") is None
    assert store.pending_challenges == 0


def test_spent_whatever_the_outcome_and_expiry():
    store = InMemoryEnrollmentStore()
    t0 = now_ms()
    c = issue_enrollment_challenge(store, authenticated_account_id="a", ttl_ms=1000, now=t0)
    proof = sign_enrollment(account_id="a", did=ALICE.did, challenge=c.challenge, audience=AUD, private_key=ALICE.priv)
    args = dict(authenticated_account_id="a", audience=AUD, did=ALICE.did, challenge=c.challenge, proof=proof)
    assert complete_enrollment(store, **args, now=t0 + 1000).code == "CHALLENGE_EXPIRED"
    assert complete_enrollment(store, **args, now=t0).code == "CHALLENGE_UNKNOWN"


def test_once_even_concurrently():
    store = InMemoryEnrollmentStore()
    c = issue_enrollment_challenge(store, authenticated_account_id="a")
    proof = sign_enrollment(account_id="a", did=ALICE.did, challenge=c.challenge, audience=AUD, private_key=ALICE.priv)
    results = []

    def run():
        results.append(complete_enrollment(store, authenticated_account_id="a", audience=AUD, did=ALICE.did,
                                           challenge=c.challenge, proof=proof))

    threads = [threading.Thread(target=run) for _ in range(8)]
    for th in threads:
        th.start()
    for th in threads:
        th.join()
    assert sum(r.ok for r in results) == 1
    assert sum(r.code == "CHALLENGE_UNKNOWN" for r in results) == 7


def test_rotation():
    store = InMemoryEnrollmentStore()
    assert enroll(store, "a", ALICE).replaced is None
    nxt = Key()
    r = enroll(store, "a", nxt)
    assert (r.ok, r.did, r.replaced) == (True, nxt.did, ALICE.did)
    assert enroll(store, "a", nxt).replaced is None
    assert enrolled_did(store, "a") == nxt.did


def test_only_self_certifying_dids_by_default():
    store = InMemoryEnrollmentStore()
    named = "did:aroha:alice"

    def attempt(**kw):
        c = issue_enrollment_challenge(store, authenticated_account_id="a")
        proof = b64u(ALICE.priv.sign(enrollment_signing_payload(audience=AUD, account_id="a", did=named, challenge=c.challenge).encode()))
        return complete_enrollment(store, authenticated_account_id="a", audience=AUD, did=named, challenge=c.challenge, proof=proof, **kw)

    assert (attempt().code, attempt().status) == ("BAD_DID", 400)
    assert attempt(resolve_public_key=lambda d: ALICE.pub if d == named else None).ok

    def boom(_d):
        raise RuntimeError("registry down")

    assert attempt(resolve_public_key=boom).code == "BAD_DID"


def test_store_failures_are_503():
    inner = InMemoryEnrollmentStore()
    c = issue_enrollment_challenge(inner, authenticated_account_id="a")
    proof = sign_enrollment(account_id="a", did=ALICE.did, challenge=c.challenge, audience=AUD, private_key=ALICE.priv)

    class Down:
        def put_challenge(self, *a): ...
        def consume_challenge(self, ch): raise RuntimeError("db")
        def get_binding(self, a): return None
        def set_binding(self, a, d): ...

    class BindFails(Down):
        def consume_challenge(self, ch): return inner.consume_challenge(ch)
        def set_binding(self, a, d): raise RuntimeError("db")

    args = dict(authenticated_account_id="a", audience=AUD, did=ALICE.did, challenge=c.challenge, proof=proof)
    assert (complete_enrollment(Down(), **args).code, complete_enrollment(Down(), **args).status) == ("STORE_UNAVAILABLE", 503)
    assert complete_enrollment(BindFails(), **args).code == "STORE_UNAVAILABLE"


def test_misconfiguration_raises_client_input_refuses():
    store = InMemoryEnrollmentStore()
    with pytest.raises(ValueError, match="authenticated_account_id"):
        issue_enrollment_challenge(store, authenticated_account_id="")
    with pytest.raises(ValueError, match="EnrollmentStore"):
        issue_enrollment_challenge(None, authenticated_account_id="a")
    for ttl in (0, -1, 2 * 3_600_000, True):
        with pytest.raises(ValueError, match="ttl_ms"):
            issue_enrollment_challenge(store, authenticated_account_id="a", ttl_ms=ttl)
    base = dict(authenticated_account_id="a", audience=AUD, did=ALICE.did, challenge="x" * 20, proof="p")
    with pytest.raises(ValueError, match="authenticated_account_id"):
        complete_enrollment(store, **{**base, "authenticated_account_id": None})
    with pytest.raises(ValueError, match="audience"):
        complete_enrollment(store, **{**base, "audience": ""})
    for ch in (None, 42, "short", "with space but long enough"):
        r = complete_enrollment(store, **{**base, "challenge": ch})
        assert (r.code, r.status) == ("MALFORMED", 400)
    with pytest.raises(ValueError, match="account_id"):
        enrolled_did(store, "")


def test_sign_enrollment():
    ch = "c" * 43
    proof = sign_enrollment(account_id="a", did=ALICE.did, challenge=ch, audience=AUD, private_key=ALICE.priv)
    payload = enrollment_signing_payload(audience=AUD, account_id="a", did=ALICE.did, challenge=ch)
    assert json.loads(payload) == {"purpose": ENROLLMENT_PURPOSE, "audience": AUD, "accountId": "a", "did": ALICE.did, "challenge": ch}
    import base64
    Ed25519PublicKey.from_public_bytes(ALICE.pub).verify(base64.urlsafe_b64decode(proof + "=="), payload.encode())
    with pytest.raises(ValueError, match="not the key"):
        sign_enrollment(account_id="a", did=ALICE.did, challenge=ch, audience=AUD, private_key=MALLORY.priv)
    with pytest.raises(ValueError, match="challenge"):
        sign_enrollment(account_id="a", did=ALICE.did, challenge="bad", audience=AUD, private_key=ALICE.priv)
    # Raw 32-byte keys work too.
    raw = ALICE.priv.private_bytes_raw()
    assert sign_enrollment(account_id="a", did=ALICE.did, challenge=ch, audience=AUD, private_key=raw) == proof


def test_in_memory_store_full():
    store = InMemoryEnrollmentStore(max_challenges=2)
    t0 = 1_000_000
    issue_enrollment_challenge(store, authenticated_account_id="a", ttl_ms=1000, now=t0)
    issue_enrollment_challenge(store, authenticated_account_id="a", ttl_ms=1000, now=t0)
    with pytest.raises(RuntimeError, match="too many"):
        issue_enrollment_challenge(store, authenticated_account_id="a", now=t0 + 999)
    issue_enrollment_challenge(store, authenticated_account_id="a", now=t0 + 1000)
    assert store.pending_challenges == 1


def test_enrolled_did_feeds_expected_root():
    store = InMemoryEnrollmentStore()
    assert enroll(store, "cust-1", ALICE).ok
    assert enroll(store, "cust-2", MALLORY).ok
    grant = issue_intent_mandate(ALICE.did, AGENT.did, SpendingConstraints(spend_limit_usd=100), ALICE.priv, 600)
    body = b'{"customerId":"cust-1","amountUsd":10}'
    h = present_mandate_http(token=grant.token, holder_did=AGENT.did, holder_private_key=AGENT.priv, audience=AUD,
                             method="POST", url=AUD + "/invoices", body=body)[HTTP_MANDATE_HEADER]
    nonces, ledger = InMemoryHttpPresentationNonces(), InMemorySpendingLedger()

    def spend(customer_id):
        return verify_http_spend_request(h, audience=AUD, method="POST", url="/invoices", body=body, nonces=nonces,
                                         is_revoked=None, ledger=ledger, amount_usd=10,
                                         expected_root=enrolled_did(store, customer_id))

    r = spend("cust-unknown")
    assert (r.code, r.status) == ("ROOT_NOT_PINNED", 403)
    assert spend("cust-2").code == "MANDATE_INVALID"
    assert spend("cust-1").ok


