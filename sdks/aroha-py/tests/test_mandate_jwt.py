def test_task_mandate_in_jwt_form() -> None:
    human, assistant, worker = Party(), Party(), Party()
    root = issue_task_mandate(human.did, assistant.did, ["inbox.read", "inbox.archive"],
                              {"actionLimits": {"inbox.archive": 20}, "maxDelegationDepth": 2}, human.priv,
                              blocked=["inbox.delete"], format="jwt")
    assert root.token == root.jwt
    assert _segment(root.jwt, 0) == {"alg": "EdDSA", "typ": MANDATE_JWT_TYP, "kid": ed25519_jwk_thumbprint(human.pub)}  # type: ignore[arg-type]
    detail = _segment(root.jwt, 1)["authorization_details"][0]  # type: ignore[arg-type]
    assert detail["type"] == "aroha_task_mandate" and detail["allowed"] == ["inbox.read", "inbox.archive"] and detail["blocked"] == ["inbox.delete"]

    assert verify_task_mandate(root.token, human.pub, assistant.did).valid
    assert verify_task_mandate(root.token, assistant.pub, assistant.did).valid is False
    assert verify_task_mandate(root.token, human.pub, worker.did).valid is False
    assert verify_task_mandate(root.token, human.pub, is_revoked=lambda mid, grantor: True).valid is False

    enforce_task_constraints(root.token, human.pub, TaskActionRequest(requested_capability="inbox.read"))
    with pytest.raises(TaskConstraintViolation):
        enforce_task_constraints(root.token, human.pub, TaskActionRequest(requested_capability="inbox.delete"))

    child = attenuate_task_mandate(root, worker.did, ["inbox.read"], {"actionLimits": {}, "maxDelegationDepth": 1}, assistant.priv)
    assert looks_like_mandate_jwt(child.token) and child.wire is not None and child.wire["parentMandateId"] == root.wire["mandateId"]  # type: ignore[index]
    assert verify_task_mandate(child.token, assistant.pub, worker.did).valid
    with pytest.raises(ValueError):
        attenuate_task_mandate(root, worker.did, ["inbox.read", "inbox.send"], {"maxDelegationDepth": 1}, assistant.priv)

    rebuilt = decode_task_mandate_token(root.token)
    assert rebuilt.wire == root.wire and rebuilt.jwt == root.token
    assert looks_like_mandate_jwt(attenuate_task_mandate(rebuilt, worker.did, ["inbox.read"], {"actionLimits": {}, "maxDelegationDepth": 1}, assistant.priv).token)


