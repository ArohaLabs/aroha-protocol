"""
Mandate presentation over plain HTTP — port of
packages/aroha-credentials/src/http-mandate.ts, byte-identical on the wire
(test-vectors/http-presentation-v1.json is generated by the TypeScript SDK and
checked here).

A mandate token on its own is a bearer credential: anyone who copies it can
spend it. A REST server must never accept the token alone. The holder (the
mandate's grantee) signs each request and the server checks that signature
before it looks at the mandate.

Wire format (spec §6.9.2)::

    Aroha-Mandate: base64url( UTF-8( JCS({token, holder, nonce, expires, proof}) ) )

``proof`` is the holder's Ed25519 signature (base64url, no padding) over the
UTF-8 bytes of the RFC 8785 JCS canonicalisation of::

    {purpose: "aroha.http-mandate-presentation/v1", audience, method (ASCII
     upper-case), target (path + query exactly as sent), bodySha256 (lower-case
     hex SHA-256 of the exact body bytes), mandateId, holder, nonce, expires}

Client::

    headers = present_mandate_http(token=token, holder_did=me, holder_private_key=key,
                                   audience="https://api.example.com", method="POST",
                                   url="https://api.example.com/v1/orders", body=raw_bytes)

Server::

    r = verify_http_mandate_request(request.headers.get("Aroha-Mandate"),
                                    audience="https://api.example.com", method=request.method,
                                    url=request.url, body=raw_bytes, nonces=NONCES,
                                    expected_root=HUMAN_DID, is_revoked=None)
"""

