def _find_vectors() -> Path | None:
    env = os.environ.get("AROHA_HTTP_PRESENTATION_VECTORS")
    if env:
        return Path(env)
    for parent in Path(__file__).resolve().parents:
        cand = parent / "packages" / "aroha-credentials" / "test-vectors" / "http-presentation-v1.json"
        if cand.is_file():
            return cand
    return None


VECTORS_PATH = _find_vectors()
V = json.loads(VECTORS_PATH.read_text(encoding="utf-8")) if VECTORS_PATH else None
needs_vectors = pytest.mark.skipif(V is None, reason="http-presentation-v1.json not found (monorepo only)")


def b64u(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def unb64u(s: str) -> bytes:
    return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))


class Key:
    def __init__(self) -> None:
        self.priv = Ed25519PrivateKey.generate()
        self.pub = self.priv.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
        self.did = "did:aroha:" + to_multibase(self.pub)


HUMAN, AGENT, OTHER = Key(), Key(), Key()
TOKEN = issue_intent_mandate(HUMAN.did, AGENT.did, SpendingConstraints(spend_limit_usd=100), HUMAN.priv, 600).token
AUD = "https://api.example.com"
URL = "https://api.example.com/v1/orders?limit=5"
BODY = b'{"item":"widget","qty":2}'


def present(**over) -> str:
    args = dict(token=TOKEN, holder_did=AGENT.did, holder_private_key=AGENT.priv, audience=AUD,
                method="POST", url=URL, body=BODY)
    args.update(over)
    return present_mandate_http(**args)[HTTP_MANDATE_HEADER]


def ctx(**over):
    c = dict(audience=AUD, method="POST", url="/v1/orders?limit=5", body=BODY, nonces=InMemoryHttpPresentationNonces())
    c.update(over)
    return c


# ── Unit ──────────────────────────────────────────────────────────────────────

def test_request_target():
    assert http_request_target("https://api.example.com/v1/pay?x=1&y=%2F#frag") == "/v1/pay?x=1&y=%2F"
    assert http_request_target("https://api.example.com") == "/"
    assert http_request_target("https://api.example.com?x=1") == "/?x=1"
    assert http_request_target("/a/%7E") == "/a/%7E"
    for bad in ["", "ftp://h/a", "//h/a", "a/b", "https://h/a b", "https://h/café", "https://h/a/../b",
                "/a/%2e%2E/b", "https://h/%zz", "https://user@h/a", "https:///a", "/a\n"]:
        with pytest.raises(ValueError):
            http_request_target(bad)


def test_round_trip_and_bodies():
    r = verify_http_presentation(present(), **ctx())
    assert r.ok and r.holder == AGENT.did and r.token == TOKEN
    assert verify_http_presentation(present(), **ctx(body=BODY.decode())).ok
    assert verify_http_presentation(present(method="get", body=None), **ctx(method="GET", body=b"")).ok
    assert http_body_sha256(None) == "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"


def test_token_alone_is_never_accepted():
    assert verify_http_presentation(None, **ctx()).code == "MISSING"
    assert verify_http_presentation(TOKEN, **ctx()).code == "MALFORMED"


@pytest.mark.parametrize("over", [
    {"audience": "https://evil.example.com"}, {"method": "PUT"}, {"url": "/v1/orders/1?limit=5"},
    {"url": "/v1/orders?limit=500"}, {"body": b'{"item":"widget","qty":200}'}, {"body": b'{"item": "widget", "qty": 2}'},
])
def test_binding(over):
    assert verify_http_presentation(present(), **ctx(**over)).code == "BAD_PROOF"


def test_replay_and_nonce_consumed_last():
    nonces = InMemoryHttpPresentationNonces()
    h = present()
    assert not verify_http_presentation(h, **ctx(nonces=nonces, method="PUT"))
    assert verify_http_presentation(h, **ctx(nonces=nonces)).ok
    assert verify_http_presentation(h, **ctx(nonces=nonces)).code == "REPLAYED"


def test_lifetime():
    h = present(ttl_ms=1000)
    assert verify_http_presentation(h, **ctx(now=now_ms() + 5000)).code == "EXPIRED"
    capped = present(ttl_ms=3_600_000)
    assert verify_http_presentation(capped, **ctx()).ok
    assert verify_http_presentation(capped, **ctx(now=now_ms() - 60_000)).code == "LIFETIME_TOO_LONG"


def test_holder_must_be_grantee_and_key_must_match():
    with pytest.raises(ValueError, match="grantee"):
        present(holder_did=OTHER.did, holder_private_key=OTHER.priv)
    wrong_key = json.loads(unb64u(present(holder_private_key=OTHER.priv)))
    assert verify_http_presentation(b64u(json.dumps(wrong_key).encode()), **ctx()).code == "BAD_PROOF"
    swapped = dict(wrong_key, holder=OTHER.did)
    assert verify_http_presentation(b64u(json.dumps(swapped).encode()), **ctx()).code == "HOLDER_NOT_GRANTEE"


def test_resolver_and_store_failures_refuse():
    h = present()
    assert verify_http_presentation(h, **ctx(resolve_public_key=lambda d: None)).code == "UNKNOWN_HOLDER"

    def boom(*_a):
        raise RuntimeError("down")

    assert verify_http_presentation(h, **ctx(resolve_public_key=boom)).code == "UNKNOWN_HOLDER"

    class Broken:
        claim = staticmethod(boom)

    assert verify_http_presentation(h, **ctx(nonces=Broken())).code == "NONCE_STORE_UNAVAILABLE"


def test_in_memory_store_refuses_when_full():
    s = InMemoryHttpPresentationNonces(max_entries=2)
    assert s.claim("a", 2000, 1000) and s.claim("b", 2000, 1000)
    assert not s.claim("c", 2000, 1000)
    assert s.claim("c", 4000, 3000)


def test_mandate_request_requires_pins():
    h = present()
    with pytest.raises(ValueError, match="pin the root"):
        verify_http_mandate_request(h, **ctx(), is_revoked=None)
    with pytest.raises(ValueError, match="expected_root"):
        verify_http_mandate_request(h, **ctx(), expected_root=42, is_revoked=None)
    with pytest.raises(ValueError, match="trusted_roots"):
        verify_http_mandate_request(h, **ctx(), trusted_roots="did:x", is_revoked=None)
    with pytest.raises(ValueError, match="trusted_roots"):
        verify_http_mandate_request(h, **ctx(), trusted_roots=[HUMAN.did, ""], is_revoked=None)
    with pytest.raises(ValueError, match="is_revoked"):
        verify_http_mandate_request(h, **ctx(), expected_root=HUMAN.did)
    with pytest.raises(ValueError, match="is_revoked"):
        verify_http_mandate_request(h, **ctx(), expected_root=None)


@pytest.mark.parametrize("pins", [
    {"expected_root": None},
    {"expected_root": ""},
    {"trusted_roots": None},
    {"trusted_roots": []},
    {"expected_root": None, "trusted_roots": []},
])
def test_supplied_but_empty_pin_refuses_without_consuming_the_nonce(pins):
    nonces = InMemoryHttpPresentationNonces()
    h = present()
    r = verify_http_mandate_request(h, **ctx(nonces=nonces), is_revoked=None, **pins)
    assert (r.ok, r.code, r.status) == (False, "ROOT_NOT_PINNED", 403)
    assert len(nonces) == 0
    assert verify_http_mandate_request(h, **ctx(nonces=nonces), expected_root=HUMAN.did, is_revoked=None).ok


def test_empty_pin_ignored_beside_a_real_one_and_bad_presentation_still_401():
    assert verify_http_mandate_request(present(), **ctx(), expected_root=None, trusted_roots=[HUMAN.did], is_revoked=None).ok
    assert verify_http_mandate_request(present(), **ctx(), expected_root=HUMAN.did, trusted_roots=[], is_revoked=None).ok
    r = verify_http_mandate_request(None, **ctx(), expected_root=None, is_revoked=None)
    assert (r.code, r.status) == ("MISSING", 401)


def test_one_injected_clock_governs_mandate_expiry():
    t0 = now_ms()
    short = issue_intent_mandate(HUMAN.did, AGENT.did, SpendingConstraints(spend_limit_usd=100), HUMAN.priv, 60).token

    def at(now, made=None):
        return verify_http_mandate_request(present(token=short, now=made if made is not None else now),
                                           **ctx(), expected_root=HUMAN.did, is_revoked=None, now=now)

    assert at(t0 + 30_000).ok
    late = at(t0 + 120_000)  # the presentation is fresh at this clock; the mandate is not
    assert (late.ok, late.code, late.status) == (False, "MANDATE_INVALID", 403)
    assert "expired" in (late.reason or "").lower()
    stale = at(t0 + 120_000, made=t0)
    assert (stale.code, stale.status) == ("EXPIRED", 401)


def test_mandate_request():
    nonces = InMemoryHttpPresentationNonces()
    h = present()
    bad = verify_http_mandate_request(h, **ctx(nonces=nonces), expected_root=OTHER.did, is_revoked=None)
    assert (bad.ok, bad.code, bad.status) == (False, "MANDATE_INVALID", 403)
    assert len(nonces) == 0
    assert verify_http_mandate_request(h, **ctx(nonces=nonces), trusted_roots=[OTHER.did], is_revoked=None).code == "MANDATE_INVALID"
    ok = verify_http_mandate_request(h, **ctx(nonces=nonces), trusted_roots=[OTHER.did, HUMAN.did], is_revoked=lambda m, g: False)
    assert ok.ok and ok.mandate.constraints.spend_limit_usd == 100 and ok.root_grantor == HUMAN.did
    assert verify_http_mandate_request(present(), **ctx(), expected_root=HUMAN.did, is_revoked=lambda m, g: True).code == "MANDATE_INVALID"


def test_mandate_request_delegated_chain():
    intent = issue_intent_mandate(HUMAN.did, AGENT.did, SpendingConstraints(spend_limit_usd=100), HUMAN.priv, 600)
    cart = attenuate_to_cart(intent, OTHER.did, SpendingConstraints(spend_limit_usd=10), AGENT.priv)
    h = present(token=cart.token, holder_did=OTHER.did, holder_private_key=OTHER.priv)
    r = verify_http_mandate_request(h, **ctx(), expected_root=HUMAN.did, is_revoked=None)
    assert r.ok and r.mandate.mandate_tier == "cart"


