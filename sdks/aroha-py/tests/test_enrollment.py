def _find_vectors() -> Path | None:
    env = os.environ.get("AROHA_ENROLLMENT_VECTORS")
    if env:
        return Path(env)
    for parent in Path(__file__).resolve().parents:
        cand = parent / "packages" / "aroha-credentials" / "test-vectors" / "enrollment-v1.json"
        if cand.is_file():
            return cand
    return None


VECTORS_PATH = _find_vectors()
V = json.loads(VECTORS_PATH.read_text(encoding="utf-8")) if VECTORS_PATH else None
needs_vectors = pytest.mark.skipif(V is None, reason="enrollment-v1.json not found (monorepo only)")

AUD = "https://invoices.example.com"


class Key:
    def __init__(self) -> None:
        self.priv = Ed25519PrivateKey.generate()
        self.pub = self.priv.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
        self.did = "did:aroha:" + to_multibase(self.pub)


ALICE, MALLORY, AGENT = Key(), Key(), Key()


def b64u(b: bytes) -> str:
    import base64
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def enroll(store, account_id, k: Key, *, signed_in_as=None, audience=AUD):
    c = issue_enrollment_challenge(store, authenticated_account_id=account_id)
    proof = sign_enrollment(account_id=account_id, did=k.did, challenge=c.challenge, audience=AUD, private_key=k.priv)
    return complete_enrollment(store, authenticated_account_id=signed_in_as or account_id, audience=audience,
                               did=k.did, challenge=c.challenge, proof=proof)


