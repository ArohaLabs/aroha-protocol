"""Request signing for ``auth="aroha-sig"`` — proving *which agent* is calling.

A bearer token is a shared secret: every holder of it is indistinguishable. For
private agents you need caller *identity*, so a signed request carries the
caller's DID and an Ed25519 signature the callee verifies against that DID's
registered public key.

Signed material (newline-joined, order fixed)::

    METHOD \\n PATH \\n TIMESTAMP \\n NONCE \\n SHA-256(body, hex)

Headers::

    X-Aroha-Did         did:aroha:caller
    X-Aroha-Timestamp   ISO-8601
    X-Aroha-Nonce       unique per request
    X-Aroha-Signature   base64url(Ed25519 signature)

Binding the method, path and a hash of the body means a captured signature
cannot be replayed against a different endpoint or with altered content; the
timestamp bounds the replay window.

This is byte-for-byte compatible with ``@aroha-sdk/run`` in TypeScript — a
request signed by either language verifies in the other. ``test_signing.py``
pins that with vectors generated by the TypeScript implementation, because
"compatible" is a claim that rots silently unless something checks it.
"""

from __future__ import annotations

import base64
import hashlib
import json
import time
import urllib.parse
import urllib.request
import uuid
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Callable, Mapping

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives.asymmetric.ed25519 import (
    Ed25519PrivateKey,
    Ed25519PublicKey,
)

__all__ = [
    "SIG_HEADERS",
    "DEFAULT_MAX_SKEW_MS",
    "VerifyResult",
    "canonical_string",
    "sign_request",
    "verify_signed_request",
    "NonceGuard",
    "registry_key_resolver",
]

SIG_HEADERS = {
    "did": "x-aroha-did",
    "timestamp": "x-aroha-timestamp",
    "nonce": "x-aroha-nonce",
    "signature": "x-aroha-signature",
}

#: Default tolerance for clock skew between caller and callee (5 minutes).
DEFAULT_MAX_SKEW_MS = 5 * 60 * 1000



def _b64url_encode(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).decode("ascii").rstrip("=")


def _b64url_decode(value: str) -> bytes:
    # Python requires the padding that base64url conventionally omits.
    padding = "=" * (-len(value) % 4)
    return base64.urlsafe_b64decode(value + padding)


def canonical_string(method: str, path: str, timestamp: str, nonce: str, body: str = "") -> str:
    """Build the exact string that gets signed.

    Kept public so an implementer can diff it against another language's output
    when signatures mysteriously fail to verify — which is nearly always a
    canonicalisation mismatch rather than a crypto problem.
    """
    body_hash = hashlib.sha256(body.encode("utf-8")).hexdigest()
    return "\n".join([method.upper(), path, timestamp, nonce, body_hash])


def _load_private_key(private_key: bytes | Ed25519PrivateKey) -> Ed25519PrivateKey:
    """Accept a raw 32-byte seed, a PKCS#8 DER blob, or an already-loaded key."""
    if isinstance(private_key, Ed25519PrivateKey):
        return private_key
    if len(private_key) == 32:
        return Ed25519PrivateKey.from_private_bytes(private_key)
    # PKCS#8 from WebCrypto: the trailing 32 bytes are the seed. Parsing the
    # full DER would drag in a heavier dependency for no benefit, since the
    # envelope for Ed25519 keys is fixed-length.
    from cryptography.hazmat.primitives.serialization import load_der_private_key

    loaded = load_der_private_key(private_key, password=None)
    if not isinstance(loaded, Ed25519PrivateKey):
        raise TypeError("private_key is not an Ed25519 key")
    return loaded


def sign_request(
    *,
    did: str,
    private_key: bytes | Ed25519PrivateKey,
    method: str,
    path: str,
    body: str = "",
    timestamp: str | None = None,
    nonce: str | None = None,
) -> dict[str, str]:
    """Sign a request as ``did``. Returns headers to merge into your call.

    ``private_key`` may be a raw 32-byte seed or a PKCS#8 DER blob (what
    WebCrypto exports), so a key generated in either language works here.
    """
    ts = timestamp or datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace(
        "+00:00", "Z"
    )
    nc = nonce or str(uuid.uuid4())
    canonical = canonical_string(method, path, ts, nc, body)

    key = _load_private_key(private_key)
    signature = key.sign(canonical.encode("utf-8"))

    return {
        SIG_HEADERS["did"]: did,
        SIG_HEADERS["timestamp"]: ts,
        SIG_HEADERS["nonce"]: nc,
        SIG_HEADERS["signature"]: _b64url_encode(signature),
    }


@dataclass
class VerifyResult:
    ok: bool
    #: The verified caller DID — only trustworthy when ``ok`` is True.
    did: str | None = None
    reason: str | None = None


def _header(headers: Mapping[str, str] | object, name: str) -> str | None:
    """Read a header case-insensitively from a dict or a framework object."""
    getter = getattr(headers, "get", None)
    if callable(getter):
        return getter(name) or getter(name.lower()) or getter(name.title())
    return None


def verify_signed_request(
    *,
    headers: Mapping[str, str],
    method: str,
    path: str,
    body: str = "",
    resolve_public_key: Callable[[str], bytes | None],
    allowed_callers: list[str] | None = None,
    max_skew_ms: int = DEFAULT_MAX_SKEW_MS,
    consume_nonce: Callable[[str, str], bool] | None = None,
) -> VerifyResult:
    """Verify a signed request, failing closed on every ambiguity.

    The ORDER of these checks is a security property, not an implementation
    detail, and mirrors the TypeScript implementation exactly:

    * The allow-list is consulted **before** the key is resolved. Resolving
      first would perform a registry lookup on behalf of an unauthorised
      caller, turning the endpoint into an oracle for "does this DID exist?"
      that is observable through latency.
    * The nonce is consumed **last**, only once everything else has passed.
      Burning it earlier would let an attacker invalidate a legitimate caller's
      request by replaying it with a broken signature — a denial of service
      delivered through the replay defence itself.
    """
    did = _header(headers, SIG_HEADERS["did"])
    timestamp = _header(headers, SIG_HEADERS["timestamp"])
    nonce = _header(headers, SIG_HEADERS["nonce"])
    signature = _header(headers, SIG_HEADERS["signature"])

    if not (did and timestamp and nonce and signature):
        return VerifyResult(False, reason="Missing signature headers")

    # Allow-list first — never spend verification work on a caller we would
    # reject, and never reveal whether an unknown DID has a resolvable key.
    if allowed_callers is not None and did not in allowed_callers:
        return VerifyResult(False, reason="Caller not permitted")

    try:
        parsed = datetime.fromisoformat(timestamp.replace("Z", "+00:00"))
        if parsed.tzinfo is None:
            parsed = parsed.replace(tzinfo=timezone.utc)
        ts_ms = parsed.timestamp() * 1000
    except ValueError:
        return VerifyResult(False, reason="Malformed timestamp")

    if abs(time.time() * 1000 - ts_ms) > max_skew_ms:
        return VerifyResult(False, reason="Timestamp outside the accepted window")

    try:
        public_key = resolve_public_key(did)
    except Exception:
        return VerifyResult(False, reason="Could not resolve caller key")
    if not public_key or len(public_key) != 32:
        return VerifyResult(False, reason="Unknown caller key")

    canonical = canonical_string(method, path, timestamp, nonce, body)
    try:
        Ed25519PublicKey.from_public_bytes(public_key).verify(
            _b64url_decode(signature), canonical.encode("utf-8")
        )
    except InvalidSignature:
        return VerifyResult(False, reason="Invalid signature")
    except Exception:
        return VerifyResult(False, reason="Signature verification error")

    # Replay guard last: only burn a nonce for an otherwise-valid request.
    if consume_nonce is not None and not consume_nonce(did, nonce):
        return VerifyResult(False, reason="Replayed nonce")

    return VerifyResult(True, did=did)


class NonceGuard:
    """In-memory replay guard, suitable for a single long-lived process.

    Multi-instance deployments should back this with a shared store — two
    processes with separate guards will each accept the same nonce once.
    """

    def __init__(self, window_ms: int = DEFAULT_MAX_SKEW_MS) -> None:
        self._window_ms = window_ms
        self._seen: dict[str, float] = {}

    def __call__(self, did: str, nonce: str) -> bool:
        now = time.time() * 1000
        # Prune expired entries so the map stays bounded without a background task.
        for key, seen_at in list(self._seen.items()):
            if now - seen_at > self._window_ms:
                del self._seen[key]

        key = f"{did}:{nonce}"
        if key in self._seen:
            return False
        self._seen[key] = now
        return True


def registry_key_resolver(
    registry_url: str | None = None,
    timeout: float = 5.0,
    *,
    allow_insecure_http: bool = False,
) -> Callable[[str], bytes | None]:
    """Resolve a caller DID to its raw Ed25519 public key via the registry.

    Returns None for anything unresolvable, so the caller is rejected rather
    than admitted on a lookup failure. ``registry_url`` must be https (or
    loopback) unless ``allow_insecure_http=True``: a key fetched over plain
    http could be substituted in transit.
    """
    from .endpoints import resolve_registry_url
    from .safety import require_secure_url

    # None → AROHA_REGISTRY_URL → AROHA_MANAGED_REGISTRY_URL (aroha.endpoints).
    registry_url = resolve_registry_url(registry_url)
    require_secure_url(registry_url, allow_insecure_http=allow_insecure_http, what="registry URL")

    cache: dict[str, bytes | None] = {}

    def resolve(did: str) -> bytes | None:
        if did in cache:
            return cache[did]

        # The registry resolves by DID directly, not by a hash of it — matching
        # registryKeyResolver in @aroha-sdk/run.
        url = f"{registry_url.rstrip('/')}/v1/agents/{urllib.parse.quote(did, safe='')}"
        try:
            with urllib.request.urlopen(url, timeout=timeout) as response:
                record = json.loads(response.read().decode("utf-8"))
        except Exception:
            # Not cached: a transient network failure should not poison the
            # cache into permanently rejecting a legitimate caller.
            return None

        encoded = record.get("publicKeyB64")
        key: bytes | None = None
        if encoded:
            try:
                # Registry stores standard base64; tolerate base64url too.
                padding = "=" * (-len(encoded) % 4)
                key = base64.b64decode(encoded.replace("-", "+").replace("_", "/") + padding)
            except Exception:
                key = None

        cache[did] = key
        return key

    return resolve
