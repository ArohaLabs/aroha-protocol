def test_running_total_refuses_the_cent_over():
    ledger = InMemorySpendingLedger()
    m = intent(spend_limit_usd=500)
    r = spend(m, ledger, amount_usd=250)
    assert r.ok and r.root_grantor == HUMAN.did and r.revocation_checked is False
    assert [k for k, _ in r.charge.allocations] == [mandate_redemption_key(m.mandate)]
    assert spend(m, ledger, amount_usd=250.01).code == "OVER_LIMIT"
    assert spend(m, ledger, amount_usd=250).ok
    assert spend(m, ledger, amount_usd=0.01).code == "OVER_LIMIT"
    assert allocated(ledger, m) == 500
    assert ledger.status(m.mandate.mandate_id) is None  # never keyed by the bare id


def test_siblings_share_the_parent_and_leaf_exhaustion_rolls_back():
    ledger = InMemorySpendingLedger()
    root = intent(spend_limit_usd=500)
    cart_a = attenuate_to_cart(root, PROVIDER_A.did, SpendingConstraints(spend_limit_usd=400), AGENT.priv)
    cart_b = attenuate_to_cart(root, PROVIDER_B.did, SpendingConstraints(spend_limit_usd=400), AGENT.priv)
    assert spend(cart_a, ledger, PROVIDER_A, amount_usd=300).ok
    assert spend(cart_b, ledger, PROVIDER_B, amount_usd=300).code == "OVER_LIMIT"
    assert allocated(ledger, cart_b) == 0
    small = attenuate_to_cart(root, PROVIDER_A.did, SpendingConstraints(spend_limit_usd=100), AGENT.priv)
    assert spend(small, ledger, PROVIDER_A, amount_usd=60).ok
    assert spend(small, ledger, PROVIDER_A, amount_usd=60).code == "OVER_LIMIT"  # fits root, not the cart
    assert allocated(ledger, root) == 360 and allocated(ledger, small) == 60


def test_release_returns_every_link_once():
    ledger = InMemorySpendingLedger()
    root = intent(spend_limit_usd=500)
    cart = attenuate_to_cart(root, PROVIDER_A.did, SpendingConstraints(spend_limit_usd=300), AGENT.priv)
    r = spend(cart, ledger, PROVIDER_A, amount_usd=300)
    assert r.ok and len(r.charge.allocations) == 2
    r.charge.release()
    r.charge.release()
    assert allocated(ledger, root) == 0 and allocated(ledger, cart) == 0


def test_concurrent_spends_cannot_both_take_the_last_of_the_budget():
    ledger = InMemorySpendingLedger()
    m = intent(spend_limit_usd=500)
    nonces = InMemoryHttpPresentationNonces()
    headers = [header(m) for _ in range(8)]
    results: list = []
    barrier = threading.Barrier(len(headers))

    def go(h):
        barrier.wait()
        results.append(verify_http_spend_request(
            h, audience=AUD, method="POST", url="/v1/invoices", body=BODY, nonces=nonces,
            expected_root=HUMAN.did, is_revoked=None, ledger=ledger, amount_usd=200))

    threads = [threading.Thread(target=go, args=(h,)) for h in headers]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    assert sum(1 for r in results if r.ok) == 2
    assert all(r.code == "OVER_LIMIT" for r in results if not r.ok)
    assert allocated(ledger, m) == 400


def test_ledger_failure_is_503_and_rolls_back():
    inner = InMemorySpendingLedger()
    root = intent(spend_limit_usd=500)
    cart = attenuate_to_cart(root, PROVIDER_A.did, SpendingConstraints(spend_limit_usd=100), AGENT.priv)
    calls = {"n": 0}

    class Flaky:
        def init(self, k, limit):
            inner.init(k, limit)

        def allocate(self, k, a):
            calls["n"] += 1
            if calls["n"] == 2:
                raise ConnectionError("reset")
            return inner.allocate(k, a)

        def release(self, k, aid):
            inner.release(k, aid)

    r = spend(cart, Flaky(), PROVIDER_A)
    assert (r.code, r.status) == ("LEDGER_UNAVAILABLE", 503)
    assert allocated(inner, root) == 0


def test_constraints():
    ledger = InMemorySpendingLedger()
    eur = intent(spend_limit_usd=100, currency="EUR")
    assert spend(eur, ledger).code == "CURRENCY_MISMATCH"
    assert spend(eur, ledger, currency="EUR").ok
    shop = intent(spend_limit_usd=100, allowed_merchants=["did:web:shop.example"])
    assert spend(shop, ledger).code == "MERCHANT_NOT_ALLOWED"
    assert spend(shop, ledger, merchant="did:web:other.example").code == "MERCHANT_NOT_ALLOWED"
    assert spend(shop, ledger, merchant="did:web:shop.example").ok
    mcc = intent(spend_limit_usd=100, merchant_category="5734")
    assert spend(mcc, ledger).code == "MERCHANT_CATEGORY_NOT_ALLOWED"
    assert spend(mcc, ledger, merchant_category="5734").ok
    gated = intent(spend_limit_usd=500, require_human_approval_above_usd=100)
    assert spend(gated, ledger, amount_usd=150).code == "HUMAN_APPROVAL_REQUIRED"
    assert spend(gated, ledger, amount_usd=150, human_approved=True).ok
    session = intent(spend_limit_usd=500, session_limit_usd=200)
    assert spend(session, ledger, amount_usd=150).ok
    assert spend(session, ledger, amount_usd=100).code == "OVER_LIMIT"


def test_invalid_amounts_are_400_and_do_not_consume_the_nonce():
    ledger = InMemorySpendingLedger()
    m = intent(spend_limit_usd=100)
    h = header(m)
    nonces = InMemoryHttpPresentationNonces()
    base = dict(audience=AUD, method="POST", url="/v1/invoices", body=BODY, nonces=nonces,
                expected_root=HUMAN.did, is_revoked=None, ledger=ledger)
    for bad in [float("nan"), float("inf"), -1, 0, 1e-7, 1e300, "5", True, None]:
        r = verify_http_spend_request(h, amount_usd=bad, **base)
        assert (r.code, r.status) == ("INVALID_AMOUNT", 400), bad
    assert verify_http_spend_request(h, amount_usd=5, **base).ok


def test_misconfiguration_raises():
    m = intent(spend_limit_usd=100)
    h = header(m)
    base = dict(audience=AUD, method="POST", url="/v1/invoices", body=BODY, nonces=InMemoryHttpPresentationNonces(),
                expected_root=HUMAN.did, is_revoked=None, amount_usd=5)
    with pytest.raises(ValueError, match="ledger is required"):
        verify_http_spend_request(h, ledger=None, **base)
    with pytest.raises(ValueError, match="merchant"):
        verify_http_spend_request(h, ledger=InMemorySpendingLedger(), merchant="", **base)
    no_hook = {k: v for k, v in base.items() if k != "is_revoked"}
    with pytest.raises(ValueError, match="is_revoked is required"):
        verify_http_spend_request(h, ledger=InMemorySpendingLedger(), **no_hook)
    no_pin = {k: v for k, v in base.items() if k != "expected_root"}
    with pytest.raises(ValueError, match="pin the root"):
        verify_http_spend_request(h, ledger=InMemorySpendingLedger(), **no_pin)


def test_empty_pin_is_a_403_refusal_not_a_crash():
    m = intent(spend_limit_usd=100)
    h = header(m)
    ledger = InMemorySpendingLedger()
    nonces = InMemoryHttpPresentationNonces()
    enrollments: dict[str, str] = {}
    for pins in [{"expected_root": enrollments.get("unknown-customer")}, {"expected_root": ""}, {"trusted_roots": []}]:
        r = spend(m, ledger, nonces=nonces, **{"expected_root": None, **pins})
        assert (r.ok, r.code, r.status) == (False, "ROOT_NOT_PINNED", 403)
    assert len(nonces) == 0 and allocated(ledger, m) == 0
    r = verify_http_spend_request(h, audience=AUD, method="POST", url="/v1/invoices", body=BODY, nonces=nonces,
                                  expected_root=HUMAN.did, is_revoked=None, ledger=ledger, amount_usd=10)
    assert r.ok


def test_one_injected_clock_governs_mandate_expiry():
    t0 = now_ms()
    m = issue_intent_mandate(HUMAN.did, AGENT.did, SpendingConstraints(spend_limit_usd=100), HUMAN.priv, 60)
    ledger = InMemorySpendingLedger()

    def at(now):
        h = present_mandate_http(token=m.token, holder_did=AGENT.did, holder_private_key=AGENT.priv, audience=AUD,
                                 method="POST", url=URL, body=BODY, now=now)[HTTP_MANDATE_HEADER]
        return verify_http_spend_request(h, audience=AUD, method="POST", url="/v1/invoices", body=BODY,
                                         nonces=InMemoryHttpPresentationNonces(), expected_root=HUMAN.did,
                                         is_revoked=None, ledger=ledger, amount_usd=10, now=now)

    assert at(t0 + 59_000).ok
    late = at(t0 + 120_000)
    assert (late.ok, late.code, late.status) == (False, "MANDATE_INVALID", 403)
    assert "expired" in (late.reason or "").lower()
    assert allocated(ledger, m) == 10


def test_ledger_unit():
    ledger = InMemorySpendingLedger()
    ledger.init("k", 0.3)
    ledger.init("k", 999)  # idempotent: first limit wins
    ids = [ledger.allocate("k", 0.1) for _ in range(3)]
    with pytest.raises(BudgetExhaustedError):
        ledger.allocate("k", 0.000001)
    ledger.release("k", ids[0])
    ledger.release("k", ids[0])
    st = ledger.status("k")
    assert (st.limit_usd, st.allocated_usd, st.allocation_count) == (0.3, 0.2, 2)
    with pytest.raises(BudgetExhaustedError):
        ledger.allocate("unknown", 1)


