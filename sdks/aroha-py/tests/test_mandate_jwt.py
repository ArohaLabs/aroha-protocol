def test_jwt_chain_between_web_identities() -> None:
    HUMAN, ASSISTANT, SHOP = "https://accounts.example.com/people/kiri", "https://agents.example.com/assistant", "https://shop.example.net/agents/checkout"
    human, assistant, shop = Party(), Party(), Party()
    published = {HUMAN: human.pub, ASSISTANT: assistant.pub, SHOP: shop.pub}

    def fetch(url: str, timeout_s: float, max_bytes: int) -> WebIdentityResponse:
        if url not in published:
            return WebIdentityResponse(404, b"")
        return WebIdentityResponse(200, json.dumps(build_web_identity_document(url, published[url])).encode())

    resolve_key = create_mandate_key_resolver(web=create_web_identity_resolver(fetch=fetch))
    intent = issue_intent_mandate(HUMAN, ASSISTANT, usd(200), human.priv, format="jwt")
    cart = attenuate_to_cart(intent, SHOP, usd(80), assistant.priv)
    r = verify_mandate_chain(cart.token, resolve_key, expected_root=HUMAN, expected_grantee=SHOP)
    assert r.valid, r.reason
    claims = _segment(cart.jwt, 1)  # type: ignore[arg-type]
    assert (claims["iss"], claims["sub"]) == (ASSISTANT, SHOP)


def test_http_presentation_of_a_jwt_form_token() -> None:
    human, assistant, other = Party(), Party(), Party()
    intent = issue_intent_mandate(human.did, assistant.did, usd(100), human.priv, 600, format="jwt")
    request = dict(audience="https://api.example.com", method="POST", url="https://api.example.com/v1/orders", body='{"item":"widget"}')

    def verify(header: str):
        return verify_http_mandate_request(
            header, audience=request["audience"], method="POST", url="/v1/orders", body=request["body"],
            nonces=InMemoryHttpPresentationNonces(), expected_root=human.did, is_revoked=None,
        )

    good = present_mandate_http(token=intent.token, holder_did=assistant.did, holder_private_key=assistant.priv, **request)
    ok = verify(good[HTTP_MANDATE_HEADER])
    assert ok.ok, getattr(ok, "reason", None)
    stolen = present_mandate_http(token=intent.token, holder_did=assistant.did, holder_private_key=other.priv, **request)
    assert verify(stolen[HTTP_MANDATE_HEADER]).ok is False


def test_peek_mandate_token() -> None:
    human, assistant, shop = Party(), Party(), Party()
    jwt_intent = issue_intent_mandate(human.did, assistant.did, usd(100), human.priv, format="jwt")
    jwt_cart = attenuate_to_cart(jwt_intent, shop.did, usd(50), assistant.priv)
    native = issue_intent_mandate(human.did, assistant.did, usd(100), human.priv)
    jwt_task = issue_task_mandate(human.did, assistant.did, ["research"], {}, human.priv, format="jwt")
    native_task = issue_task_mandate(human.did, assistant.did, ["research"], {}, human.priv)

    leaf = peek_mandate_token(jwt_cart.token)
    assert leaf is not None and (leaf.kind, leaf.format, leaf.mandate_id, leaf.grantor, leaf.grantee) == ("spending", "jwt", jwt_cart.mandate.mandate_id, assistant.did, shop.did)
    n = peek_mandate_token(native.token)
    assert n is not None and (n.kind, n.format, n.mandate_id) == ("spending", "native", native.mandate.mandate_id)
    assert peek_mandate_token(jwt_task.token).kind == "task" and peek_mandate_token(jwt_task.token).format == "jwt"  # type: ignore[union-attr]
    assert peek_mandate_token(native_task.token).kind == "task"  # type: ignore[union-attr]
    for bad in (None, 7, "", "a.b.c", "not-a-token", "e30"):
        assert peek_mandate_token(bad) is None
