"""Cross-SDK conformance: packages/aroha-credentials/test-vectors/mandate-v2.json.

Generated by the TypeScript reference (packages/aroha-credentials/scripts/
gen-test-vectors.ts). Checks every JCS case, every signing payload and
signature byte for byte, and every token verdict.

The vector file lives in the monorepo, not in the wheel: when the package is
tested standalone (outside the repo) these tests are skipped. Set
AROHA_MANDATE_VECTORS to point at a copy of the file to run them anyway.
"""

import json
import os
from pathlib import Path

import pytest
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

from aroha.jcs import canonicalize_jcs
from aroha.mandate import (
    decode_mandate_token,
    mandate_signing_payload_v2,
    resolve_content_addressed_key,
    verify_mandate,
    verify_mandate_chain,
)
from aroha.timeutil import parse_iso_ms


def _find_vectors() -> Path | None:
    env = os.environ.get("AROHA_MANDATE_VECTORS")
    if env:
        return Path(env)
    for parent in Path(__file__).resolve().parents:
        cand = parent / "packages" / "aroha-credentials" / "test-vectors" / "mandate-v2.json"
        if cand.is_file():
            return cand
    return None


VECTORS_PATH = _find_vectors()
pytestmark = pytest.mark.skipif(
    VECTORS_PATH is None,
    reason="mandate-v2.json not found (packages/aroha-credentials/test-vectors/ is only present in the "
    "monorepo checkout; set AROHA_MANDATE_VECTORS to run these conformance tests standalone)",
)
V = json.loads(VECTORS_PATH.read_text(encoding="utf-8")) if VECTORS_PATH else {"jcs": [], "mandates": [], "tokens": [], "keys": {}}


def _b64url(b: bytes) -> str:
    import base64
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


@pytest.mark.parametrize("case", V["jcs"], ids=[c["name"] for c in V["jcs"]])
def test_jcs(case):
    assert canonicalize_jcs(json.loads(case["input"])) == case["expected"]


@pytest.mark.parametrize("name", list(V["keys"]))
def test_keys_and_content_addressed_dids(name):
    k = V["keys"][name]
    priv = Ed25519PrivateKey.from_private_bytes(bytes.fromhex(k["privateKeyHex"]))
    from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat
    pub = priv.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
    assert pub.hex() == k["publicKeyHex"]
    assert resolve_content_addressed_key(k["did"]) == pub


@pytest.mark.parametrize("case", V["mandates"], ids=[c["name"] for c in V["mandates"]])
def test_signing_payload_and_signature_byte_exact(case):
    payload = mandate_signing_payload_v2(case["mandate"])
    assert payload == case["expectedSigningPayload"]
    priv = Ed25519PrivateKey.from_private_bytes(bytes.fromhex(V["keys"][case["signer"]]["privateKeyHex"]))
    assert _b64url(priv.sign(payload.encode("utf-8"))) == case["expectedSignature"]


@pytest.mark.parametrize("case", V["tokens"], ids=[c["name"] for c in V["tokens"]])
def test_token_verdicts(case):
    now = parse_iso_ms(case["verifyAt"])
    result = verify_mandate_chain(case["token"], now=now)
    exp = case["expected"]
    assert result.valid is exp["valid"], result.reason
    if exp["valid"]:
        assert result.chain_verified
        assert result.root_grantor == exp["rootGrantor"]
        assert result.mandate.mandate_id == exp["leafMandateId"]
    else:
        reason = result.reason.lower()
        if exp["reasonClass"] == "narrowing":
            assert "cannot attenuate" in reason
        elif exp["reasonClass"] == "time":
            assert "valid" in reason or "expired" in reason
        else:  # pragma: no cover - new class added to the vectors
            pytest.fail(f"unknown reasonClass {exp['reasonClass']}")


def test_valid_token_through_verify_mandate_with_leaf_key():
    case = next(t for t in V["tokens"] if t["expected"]["valid"])
    agent_pub = bytes.fromhex(V["keys"]["agent"]["publicKeyHex"])
    r = verify_mandate(case["token"], agent_pub, now=parse_iso_ms(case["verifyAt"]))
    assert r.valid and r.chain_verified, r.reason
    decoded = decode_mandate_token(case["token"])
    assert decoded.v == 2 and len(decoded.chain) == 1
    assert decoded.mandate.constraints.spend_limit_usd == 42.07


def test_expected_root_mismatch_fails():
    case = next(t for t in V["tokens"] if t["expected"]["valid"])
    r = verify_mandate_chain(
        case["token"], expected_root=V["keys"]["agent"]["did"], now=parse_iso_ms(case["verifyAt"])
    )
    assert not r.valid and "root mismatch" in r.reason
