def _find_vectors() -> Path | None:
    env = os.environ.get("AROHA_HTTP_SPEND_VECTORS")
    if env:
        return Path(env)
    for parent in Path(__file__).resolve().parents:
        cand = parent / "packages" / "aroha-credentials" / "test-vectors" / "http-spend-v1.json"
        if cand.is_file():
            return cand
    return None


VECTORS_PATH = _find_vectors()
V = json.loads(VECTORS_PATH.read_text(encoding="utf-8")) if VECTORS_PATH else None
needs_vectors = pytest.mark.skipif(V is None, reason="http-spend-v1.json not found (monorepo only)")


class Key:
    def __init__(self) -> None:
        self.priv = Ed25519PrivateKey.generate()
        self.pub = self.priv.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
        self.did = "did:aroha:" + to_multibase(self.pub)


HUMAN, AGENT, PROVIDER_A, PROVIDER_B = Key(), Key(), Key(), Key()
AUD = "https://api.example.com"
URL = "https://api.example.com/v1/invoices"
BODY = b'{"customer":"c1"}'


def intent(**c):
    return issue_intent_mandate(HUMAN.did, AGENT.did, SpendingConstraints(**c), HUMAN.priv, 600)


def header(m, holder: Key = AGENT) -> str:
    return present_mandate_http(token=m.token, holder_did=holder.did, holder_private_key=holder.priv,
                                audience=AUD, method="POST", url=URL, body=BODY)[HTTP_MANDATE_HEADER]


def spend(m, ledger, holder: Key = AGENT, nonces=None, **over):
    args = dict(audience=AUD, method="POST", url="/v1/invoices", body=BODY,
                nonces=nonces or InMemoryHttpPresentationNonces(), expected_root=HUMAN.did, is_revoked=None,
                ledger=ledger, amount_usd=10)
    args.update(over)
    return verify_http_spend_request(header(m, holder), **args)


def allocated(ledger, m) -> float:
    st = ledger.status(mandate_redemption_key(m.mandate))
    return st.allocated_usd if st else 0


