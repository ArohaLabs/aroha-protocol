"""Cross-SDK conformance: packages/aroha-credentials/test-vectors/task-mandate-v2-cases.json.

Generated by the TypeScript reference (packages/aroha-credentials/scripts/
gen-task-test-vectors.ts). Checks every signing payload and signature byte
for byte, every token verdict and reason, every narrowing reason and every
action verdict (code and message).

Skipped outside the monorepo; set AROHA_TASK_MANDATE_VECTORS to a copy of the
file to run standalone.
"""

import json
import os
from pathlib import Path

import pytest
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

from aroha.task_mandate import (
    TaskActionRequest,
    check_task_constraints,
    check_task_narrowing,
    decode_task_mandate_token,
    task_mandate_signing_payload_v2,
    verify_task_mandate,
)
from aroha.timeutil import parse_iso_ms


def _find_vectors() -> Path | None:
    env = os.environ.get("AROHA_TASK_MANDATE_VECTORS")
    if env:
        return Path(env)
    for parent in Path(__file__).resolve().parents:
        cand = parent / "packages" / "aroha-credentials" / "test-vectors" / "task-mandate-v2-cases.json"
        if cand.is_file():
            return cand
    return None


VECTORS_PATH = _find_vectors()
pytestmark = pytest.mark.skipif(
    VECTORS_PATH is None,
    reason="task-mandate-v2-cases.json not found (only present in the monorepo checkout; "
    "set AROHA_TASK_MANDATE_VECTORS to run standalone)",
)
V = (json.loads(VECTORS_PATH.read_text(encoding="utf-8")) if VECTORS_PATH
     else {"mandates": [], "tokens": [], "narrowing": [], "actions": [], "keys": {}})
MANDATES = {m["name"]: m["mandate"] for m in V["mandates"]}


def _b64url(b: bytes) -> str:
    import base64
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def _pub(name: str) -> bytes:
    return bytes.fromhex(V["keys"][name]["publicKeyHex"])


@pytest.mark.parametrize("case", V["mandates"], ids=[c["name"] for c in V["mandates"]])
def test_signing_payload_and_signature_byte_exact(case):
    payload = task_mandate_signing_payload_v2(case["mandate"])
    assert payload == case["expectedSigningPayload"]
    priv = Ed25519PrivateKey.from_private_bytes(bytes.fromhex(V["keys"][case["signer"]]["privateKeyHex"]))
    assert _b64url(priv.sign(payload.encode("utf-8"))) == case["expectedSignature"]


@pytest.mark.parametrize("case", V["tokens"], ids=[c["name"] for c in V["tokens"]])
def test_token_verdicts_and_reasons(case):
    r = verify_task_mandate(
        case["token"], _pub(case["signer"]), case.get("expectedGrantee"), now=parse_iso_ms(case["verifyAt"])
    )
    assert r.valid is case["expected"]["valid"], r.reason
    assert r.reason == case["expected"]["reason"]
    if r.valid:
        # The snake_case view round-trips to the exact signed body.
        assert r.mandate.to_wire() == r.wire == decode_task_mandate_token(case["token"]).wire


@pytest.mark.parametrize("case", V["narrowing"], ids=[c["name"] for c in V["narrowing"]])
def test_narrowing_reasons(case):
    assert check_task_narrowing(case["parent"], case["child"]) == case["expectedReason"]


def _request(r: dict) -> TaskActionRequest:
    cc = r.get("currentCompute")
    return TaskActionRequest(
        requested_capability=r["requestedCapability"],
        current_action_counts=r.get("currentActionCounts"),
        current_compute=({"llm_tokens": cc.get("llmTokens"), "web_requests": cc.get("webRequests"),
                          "wall_clock_ms": cc.get("wallClockMs")} if cc is not None else None),
        capability_reversibility=r.get("capabilityReversibility"),
        data_access=r.get("dataAccess"),
        human_approved=r.get("humanApproved", False),
        room_id=r.get("roomId"),
        on_behalf_of=r.get("onBehalfOf"),
    )


@pytest.mark.parametrize("case", V["actions"], ids=[c["name"] for c in V["actions"]])
def test_action_verdicts(case):
    v = check_task_constraints(MANDATES[case["mandate"]], _request(case["request"]))
    if case["expected"] is None:
        assert v is None, str(v)
    else:
        assert v is not None
        assert (v.code, str(v)) == (case["expected"]["code"], case["expected"]["message"])
