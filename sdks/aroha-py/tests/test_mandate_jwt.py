"""The JWT form of a mandate (spec §6.10): the same mandate and chain rules, readable by a stock JWT library.

The shared cases come from packages/aroha-credentials/test-vectors/
mandate-jwt-v1.json, generated by the TypeScript reference. They are skipped
when that file is absent (set AROHA_MANDATE_JWT_VECTORS to run them outside
the monorepo). The rest covers issuing in Python, the HTTP presentation and
web identities.
"""

